#!/bin/bash
# Manage Talon's SSM parameters under /talon/<env>/ (default demo) without
# ever showing a secret value.
#
#   infra/scripts/secrets.sh [list]                 names, type, version, last change, who manages it
#   infra/scripts/secrets.sh set <name>             add or replace a secret: type it twice (hidden)
#   infra/scripts/secrets.sh set <name> --from-file <path>   ...or read it from a file (e.g. a .pem)
#   infra/scripts/secrets.sh rm <name>              delete a secret made by hand (asks you to type its name)
#
# <name> is the short name (github-app-client-secret) or the full path.
# Values are stored as SecureString with the Talon secrets key
# (alias/talon-<env>-secrets).
#
# Typing a secret here is safe: it is read with `read -s` (not echoed, not
# in shell history), never passed on a command line (not visible in ps),
# written only to a temp file readable by you alone that the AWS CLI reads
# and that is deleted straight after, and never printed. Run it in a normal
# terminal, not through an assistant or a logged session.
#
# Off limits here, by design:
#   - Parameters Terraform manages (tag ManagedBy=terraform): change the
#     variable in infra/ec2/terraform.tfvars and apply instead.
#   - session-secret and credentials-key: the web servers generate them at
#     first boot. Replacing session-secret signs everyone out; replacing
#     credentials-key without the rotation steps in
#     backend/src/utils/credentialCrypto.js makes every stored GitHub and
#     Google link unreadable. Deleting either breaks the app.
source "$(dirname "$0")/common.sh"

PREFIX="/talon/$TALON_ENV"
KMS_KEY="alias/talon-$TALON_ENV-secrets"
PROTECTED=" session-secret credentials-key "
USAGE="usage: secrets.sh [list] | set <name> [--from-file <path>] | rm <name>"

die() { echo "$*" >&2; exit 1; }

# Short name -> full name under the prefix; refuses anything else.
full_name() {
  local name="${1#"$PREFIX/"}"
  [[ "$name" =~ ^[a-z0-9][a-z0-9-]{0,99}$ ]] || die "Name must be lowercase letters, digits and dashes (like github-app-client-secret), under $PREFIX/"
  echo "$PREFIX/$name"
}

managed_by_terraform() {
  local tag
  tag="$(aws ssm list-tags-for-resource --resource-type Parameter --resource-id "$1" \
    --query "TagList[?Key=='ManagedBy'].Value | [0]" --output text 2>/dev/null || true)"
  [ "$tag" = "terraform" ]
}

# Type, or nothing when the parameter does not exist.
param_type() {
  aws ssm describe-parameters --parameter-filters "Key=Name,Option=Equals,Values=$1" \
    --query 'Parameters[0].Type' --output text 2>/dev/null | sed '/^None$/d'
}

refuse_if_off_limits() {
  local full="$1" short="${1##*/}"
  if [[ "$PROTECTED" == *" $short "* ]]; then
    die "$short is generated by the web servers and must not be changed or removed here (see the top of this script)."
  fi
  if managed_by_terraform "$full"; then
    die "$short is managed by Terraform: change it in infra/ec2/terraform.tfvars and apply."
  fi
}

cmd_list() {
  local names
  names="$(aws ssm describe-parameters \
    --parameter-filters "Key=Name,Option=BeginsWith,Values=$PREFIX/" \
    --query 'Parameters[].Name' --output text | tr '\t' '\n' | sed '/^$/d' | sort)"
  [ -n "$names" ] || { echo "No parameters under $PREFIX/"; return; }
  printf '%-34s %-13s %4s  %-16s  %s\n' "NAME ($PREFIX/)" "TYPE" "VER" "LAST CHANGED" "MANAGED BY"
  local name info type version changed who
  while read -r name; do
    info="$(aws ssm describe-parameters --parameter-filters "Key=Name,Option=Equals,Values=$name" \
      --query 'Parameters[0].[Type,Version,LastModifiedDate]' --output text)"
    read -r type version changed <<<"$info"
    if [[ "$PROTECTED" == *" ${name##*/} "* ]]; then
      who="web servers (first boot)"
    elif managed_by_terraform "$name"; then
      who="terraform"
    else
      who="by hand"
    fi
    printf '%-34s %-13s %4s  %-16s  %s\n' "${name#"$PREFIX/"}" "$type" "$version" "${changed:0:16}" "$who"
  done <<<"$names"
}

cmd_set() {
  local full from_file=""
  full="$(full_name "${1:-}")"
  shift || true
  if [ "${1:-}" = "--from-file" ]; then
    from_file="${2:-}"
    [ -n "$from_file" ] && [ -f "$from_file" ] && [ -r "$from_file" ] || die "Cannot read file: ${from_file:-<missing>}"
    [ -s "$from_file" ] || die "File is empty: $from_file"
  elif [ -n "${1:-}" ]; then
    die "$USAGE"
  fi

  local existing overwrite=()
  existing="$(param_type "$full")"
  if [ -n "$existing" ]; then
    refuse_if_off_limits "$full"
    [ "$existing" = "SecureString" ] || echo "Note: ${full##*/} is a $existing now; it will become a SecureString."
    read -r -p "Replace the current value of ${full##*/}? [y/N] " answer
    [[ "$answer" =~ ^[yY]$ ]] || die "Nothing changed."
    overwrite=(--overwrite)
  else
    [[ "$PROTECTED" == *" ${full##*/} "* ]] && die "${full##*/} is generated by the web servers; do not create it by hand."
  fi

  # Private temp folder; the value file is removed however the script ends.
  # Global, not local: the EXIT trap runs after this function has returned.
  SECRETS_TMPDIR="$(mktemp -d)"
  chmod 700 "$SECRETS_TMPDIR"
  trap 'rm -rf "${SECRETS_TMPDIR:-}"' EXIT
  local tmpdir="$SECRETS_TMPDIR"
  local value_file="$tmpdir/value"

  if [ -n "$from_file" ]; then
    cp "$from_file" "$value_file"
  else
    [ -t 0 ] || die "Type the value in a terminal (or use --from-file)."
    local first second
    read -r -s -p "Value for ${full##*/} (hidden): " first; echo
    read -r -s -p "Again: " second; echo
    [ -n "$first" ] || die "Empty value; nothing changed."
    [ "$first" = "$second" ] || die "The two values differ; nothing changed."
    # printf is a shell builtin: the value never appears in a process list.
    (umask 077; printf '%s' "$first" >"$value_file")
    first=""; second=""
  fi
  chmod 600 "$value_file"

  aws ssm put-parameter --name "$full" --type SecureString --key-id "$KMS_KEY" \
    --description "Set by hand with infra/scripts/secrets.sh" \
    --value "file://$value_file" ${overwrite[@]+"${overwrite[@]}"} \
    --query 'Version' --output text >/dev/null
  rm -f "$value_file"
  echo "Saved ${full##*/} (SecureString, $KMS_KEY). The web servers pick it up within a minute."
}

cmd_rm() {
  local full
  full="$(full_name "${1:-}")"
  [ -n "$(param_type "$full")" ] || die "${full##*/} does not exist."
  refuse_if_off_limits "$full"
  echo "Deleting ${full##*/} cannot be undone; whatever uses it stops working."
  read -r -p "Type its name to delete it: " answer
  [ "$answer" = "${full##*/}" ] || die "Name did not match; nothing deleted."
  aws ssm delete-parameter --name "$full"
  echo "Deleted ${full##*/}."
}

case "${1:-list}" in
  list) cmd_list ;;
  set) shift; cmd_set "$@" ;;
  rm) shift; cmd_rm "$@" ;;
  -h|--help|help) sed -n '2,30p' "$0" | sed 's/^# \{0,1\}//' ;;
  *) die "$USAGE" ;;
esac
